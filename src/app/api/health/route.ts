import { NextResponse } from "next/server";
import { sql } from "drizzle-orm";
import { db } from "@/db";

export const dynamic = "force-dynamic";

/**
 * Deployment self-check. Open /api/health after deploying and it tells you
 * exactly which piece is missing, instead of leaving you with a bare
 * "server-side exception" and a digest.
 *
 * Reports only whether each secret is *present* — never its value.
 */
export async function GET() {
  // "missing" and "empty" look the same to most checks, but they mean very
  // different things: empty means the variable was added and its value did not
  // save — a much easier mistake to make than forgetting it entirely.
  const describe = (name: string) => {
    const raw = process.env[name];
    if (raw === undefined) return "missing";
    if (raw.trim() === "") return "present but EMPTY — the value did not save";
    return `set (${raw.trim().length} characters)`;
  };

  const isUsable = (name: string) => (process.env[name] ?? "").trim() !== "";

  const env = {
    DATABASE_URL: describe("DATABASE_URL"),
    AUTH_SECRET: isUsable("AUTH_SECRET")
      ? describe("AUTH_SECRET")
      : "not set — fine, the app generates and stores its own session secret",
    CRON_SECRET: describe("CRON_SECRET"),
    NEXT_PUBLIC_VAPID_PUBLIC_KEY: describe("NEXT_PUBLIC_VAPID_PUBLIC_KEY"),
    VAPID_PRIVATE_KEY: describe("VAPID_PRIVATE_KEY"),
    ANTHROPIC_API_KEY: describe("ANTHROPIC_API_KEY"),
    ALLOW_SIGNUP: describe("ALLOW_SIGNUP"),
  };

  const problems: string[] = [];

  // DATABASE_URL is the only variable that must be set by hand. Everything
  // else is either optional or generated by the app itself.
  if (!isUsable("DATABASE_URL")) {
    problems.push(
      process.env.DATABASE_URL === undefined
        ? "DATABASE_URL is missing. In Vercel open the Storage tab, create a Neon Postgres database, then redeploy — Vercel fills this in for you."
        : "DATABASE_URL exists but its value is empty. Delete that variable, then create the database from Vercel's Storage tab so the value is filled in automatically, and redeploy.",
    );
  }
  if (isUsable("AUTH_SECRET") && process.env.AUTH_SECRET!.trim().length < 16) {
    problems.push(
      "AUTH_SECRET is set but shorter than 16 characters. Either lengthen it or delete it — the app generates its own secret when it is absent.",
    );
  }

  let database: Record<string, unknown> = { reachable: false };

  if (isUsable("DATABASE_URL")) {
    try {
      const rows = await db.execute<{ table_name: string }>(sql`
        select table_name
        from information_schema.tables
        where table_schema = 'public'
        order by table_name
      `);
      const tables = rows.map((r) => r.table_name);
      const expected = [
        "body_metrics",
        "exercises",
        "meals",
        "notes",
        "photo_analyses",
        "photos",
        "push_subscriptions",
        "reminders",
        "routine_days",
        "routine_exercises",
        "set_logs",
        "users",
        "water_logs",
        "workouts",
      ];
      const missing = expected.filter((t) => !tables.includes(t));

      let accounts: number | string = "unknown";
      if (missing.length === 0) {
        const [row] = await db.execute<{ n: number }>(
          sql`select count(*)::int as n from users`,
        );
        accounts = row?.n ?? 0;
        if (accounts === 0) {
          problems.push(
            'No account has been created yet. Open /login and use "Create your account" — the first account is always allowed, even with ALLOW_SIGNUP=false.',
          );
        }
      }

      database = {
        reachable: true,
        tableCount: tables.length,
        missingTables: missing,
        accounts,
      };

      if (missing.length > 0) {
        problems.push(
          `The database is missing ${missing.length} table(s). Redeploy — the build applies migrations — or run "npm run db:migrate" locally.`,
        );
      }
    } catch (error) {
      database = { reachable: false, error: redact(error) };
      problems.push(`Could not reach the database: ${redact(error)}`);
    }
  }

  return NextResponse.json(
    {
      status: problems.length === 0 ? "ok" : "needs attention",
      checkedAt: new Date().toISOString(),
      problems,
      env,
      database,
      pushNotifications:
        isUsable("NEXT_PUBLIC_VAPID_PUBLIC_KEY") && isUsable("VAPID_PRIVATE_KEY")
          ? "configured"
          : "off — add the VAPID keys to enable reminders",
      aiPhotoAnalysis: isUsable("ANTHROPIC_API_KEY") ? "configured" : "off — optional",
      note: "Environment variables only reach a deployment built after they were saved — always redeploy after changing them.",
      signupsOpen:
        (process.env.ALLOW_SIGNUP ?? "true").trim().toLowerCase() === "false"
          ? "closed by ALLOW_SIGNUP — but the first account is still allowed"
          : "open",
    },
    { status: 200 },
  );
}

/** Never echo a connection string (and its password) back over HTTP. */
function redact(error: unknown): string {
  const message = error instanceof Error ? error.message : String(error);
  return message.replace(/postgres(?:ql)?:\/\/[^\s"']+/gi, "postgresql://[redacted]");
}
